-- Учебная песочница для приёмов работы с базой.
--
-- Часть глав учит транзакциям, откату и порядку очистки — это требует права
-- записи. Писать в доменные таблицы SUT тестам нельзя: состояние меняется
-- только через публичные границы. Поэтому verification role получает
-- отдельную схему, где может создавать и удалять собственные таблицы.
--
-- Права на доменные таблицы при этом не меняются: `sut_reader` остаётся
-- read-only для `users`, `work_items` и остальных.

-- Песочница одна на базу и не зависит от схемы, в которую применяется
-- миграция: тесты миграционного движка используют временные схемы, поэтому
-- создание должно быть идемпотентным.
CREATE SCHEMA IF NOT EXISTS sandbox;

GRANT USAGE ON SCHEMA sandbox TO sut_reader;
GRANT CREATE ON SCHEMA sandbox TO sut_reader;
